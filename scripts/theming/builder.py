"""Builds base16 themes from a few seed colors (themes/seeds/*.toml).

Usage: python3 -m theming.builder themes/seeds/pony.toml [--check]
Each seed gives a tint (backgrounds), a text color, an accent and optional
colors placed on hue slots; the builder derives a full, readable palette.
"""
from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

from .colors import Color
from .hues import from_hls, hls, hue_problems, readable

SLOTS = {"red": "base08", "orange": "base09", "yellow": "base0A", "green": "base0B",
         "cyan": "base0C", "blue": "base0D", "purple": "base0E", "pink": "base0F"}
DEFAULT_HUES = {"base08": 350, "base09": 25, "base0A": 48, "base0B": 125,
                "base0C": 180, "base0D": 215, "base0E": 275, "base0F": 325}
# Lightness of the neutral slots: backgrounds (00-04) then text (05-07).
NEUTRALS = {
    "dark": (0.13, 0.10, 0.20, 0.36, 0.55, 0.86, 0.91, 0.95),
    "light": (0.95, 0.91, 0.85, 0.60, 0.45, 0.22, 0.16, 0.10),
}
TEXT_CONTRAST, ACCENT_CONTRAST = 7.0, 4.5


class BuildError(ValueError):
    """A seed cannot give a valid, readable theme."""


def build_theme(seed: dict) -> dict:
    variant = seed.get("variant", "dark")
    if variant not in NEUTRALS:
        raise BuildError(f"{seed.get('name')}: variant must be dark or light")
    tint_hue, _, tint_sat = hls(Color.parse(seed["tint"]))
    text_hue, _, text_sat = hls(Color.parse(seed["text"]))
    colors: dict[str, Color] = {}
    for index, lightness in enumerate(NEUTRALS[variant]):
        hue, sat = (tint_hue, _clamp(tint_sat * 0.6, 0.12, 0.40)) if index < 5 else \
                   (text_hue, _clamp(text_sat * 0.6, 0.15, 0.55))
        colors[f"base0{index}"] = from_hls(hue, lightness, sat)
    colors["base05"] = _readable(colors["base05"], colors["base00"], variant, TEXT_CONTRAST)
    slots = seed.get("slots", {})
    if unknown := sorted(set(slots) - set(SLOTS)):
        raise BuildError(f"{seed['name']}: unknown slot(s) {', '.join(unknown)}")
    # Hues without a canon color start pastel, so they sit well next to the seeds.
    pastel = 0.74 if variant == "dark" else 0.40
    for name, slot in SLOTS.items():
        start = Color.parse(slots[name]) if name in slots else from_hls(DEFAULT_HUES[slot] / 360, pastel, 0.62)
        colors[slot] = _readable(start, colors["base00"], variant, ACCENT_CONTRAST)
    if problems := hue_problems(colors):
        raise BuildError(f"{seed['name']}: " + "; ".join(problems))
    # The signature color, and optionally a second canon color used sparingly
    # (accent3); the lighter companion (accent2) is derived at generation.
    accents = {key: _readable(Color.parse(seed[key]), colors["base00"], variant, ACCENT_CONTRAST)
               for key in ("accent", "accent2", "accent3") if key in seed}
    return {"name": seed["name"], "variant": variant, "accents": accents, "colors": colors}


def _clamp(value: float, low: float, high: float) -> float:
    return min(max(value, low), high)


def _readable(color: Color, background: Color, variant: str, minimum: float) -> Color:
    try:
        return readable(color, background, variant, minimum)
    except ValueError as error:
        raise BuildError(str(error)) from None


def render(theme: dict, family: str, credit: str, source: str) -> str:
    lines = [
        f"# Generated by `python3 -m theming.builder {source}`: edit the seeds, not this file.",
        f"# {credit}",
        f'name    = "{theme["name"]}"',
        f'family  = "{family}"',
        f'variant = "{theme["variant"]}"',
        f'author  = "{credit}"',
        *(f'{key:<7} = "{color.hex()}"' for key, color in theme["accents"].items()),
        "",
        "[colors]",
    ]
    lines += [f'{slot} = "{color.hex()}"' for slot, color in theme["colors"].items()]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="builder", description="Build base16 themes from seeds.")
    parser.add_argument("seeds", type=Path)
    parser.add_argument("--check", action="store_true", help="fail if the theme files are out of date")
    args = parser.parse_args(argv)
    with args.seeds.open("rb") as handle:
        data = tomllib.load(handle)
    themes_dir = args.seeds.resolve().parent.parent
    source = f"themes/seeds/{args.seeds.name}"
    stale = []
    try:
        for key, seed in data["themes"].items():
            text = render(build_theme(seed), data["family"], data["credit"], source)
            target = themes_dir / f"{data['prefix']}-{key}.toml"
            if args.check:
                if not target.exists() or target.read_text() != text:
                    stale.append(target.name)
            else:
                target.write_text(text)
                print(f"  {target.name}")
    except (BuildError, KeyError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if stale:
        print(f"out of date, run the builder: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

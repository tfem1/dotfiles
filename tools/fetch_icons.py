def fetch(name: str, filled: bool) -> str:
    suffix = "_fill1_24px" if filled else "_24px"
    url = f"{BASE}/{name}/materialsymbolsrounded/{name}{suffix}.svg"
    with urllib.request.urlopen(url, timeout=30) as response:
        svg = response.read().decode()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1:
        raise ValueError(f"{name}: expected one path, found {len(paths)}")
    return paths[0]


def main() -> int:
    lines = []
    for name, filled in ICONS.items():
        lines.append(f'    "{name}": "{fetch(name, filled)}",')
    target = ROOT / "quickshell/components/icons.js"
    target.write_text(
        ".pragma library\n"
        "// Generated by tools/fetch_icons.py from Material Symbols Rounded\n"
        "// (google/material-design-icons, Apache-2.0). Do not edit by hand.\n\n"
        "const PATHS = {\n" + "\n".join(lines) + "\n};\n\n"
        "// An SVG image of the icon in the given color, as a data URL for Image.source.\n"
        "function source(name, color) {\n"
        "    const path = PATHS[name] || PATHS[\"error\"];\n"
        "    const svg = \"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 -960 960 960'>\"\n"
        "        + \"<path fill='\" + color + \"' d='\" + path + \"'/></svg>\";\n"
        "    return \"data:image/svg+xml;utf8,\" + encodeURIComponent(svg);\n"
        "}\n"
    )
    print(f"{len(ICONS)} icons -> {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
